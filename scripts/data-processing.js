// ==========================================
// CONSTANTS
// ==========================================
// Prefer the processed CSV created by `python_scripts/download_oni_to_csv.py`.
// This avoids remote CORS/network issues when loading from the browser.
const ONI_DATA_URL = "./python_scripts/data/oni_monthly.csv";
const WORLD_BANK_API_BASE = "https://api.worldbank.org/v2";
const GDP_INDICATOR = "NY.GDP.MKTP.KD.ZG";
// Local fallback for ONI (use if network fetch fails or CORS blocks remote request)
const LOCAL_ONI_DATA = "./python_scripts/data/oni.data";

// Local files (preprocessed from NetCDF/restricted sources)
// Updated to point at the CSVs generated by the preprocessing scripts
const LOCAL_FISHING_DATA = "./python_scripts/data/fishing_by_country_year.csv";
const LOCAL_RAINFALL_DATA = "./python_scripts/data/rainfall_by_country.csv";
const LOCAL_TEMPERATURE_DATA = "./python_scripts/data/temperature_by_country.csv";

// Data storage
let allData = {
    oni: null,
    gdp: null,
    fishing: null,
    rainfall: null,
    temperature: null
};

// ==========================================
// 1. ONI DATA (El Niño/La Niña)
// ==========================================
const loadONIData = async () => {
    try {
        updateStatus('oni', 'loading', 'Loading ONI data (CSV preferred)...');

        // Prefer loading the preprocessed CSV (no CORS issues when served locally)
        try {
            const csv = await d3.csv(ONI_DATA_URL, d => ({
                date: d.date ? new Date(d.date) : (d.year && d.month ? new Date(+d.year, +d.month - 1, 1) : null),
                year: d.year ? +d.year : (d.date ? new Date(d.date).getFullYear() : NaN),
                month: d.month ? +d.month : (d.date ? new Date(d.date).getMonth() + 1 : NaN),
                oni: d.oni ? +d.oni : (d.ONI ? +d.ONI : NaN),
                phase: d.phase || null,
                intensity: d.intensity || null
            }));

            if (csv && csv.length) {
                allData.oni = csv.filter(d => d.date && !isNaN(d.oni));
                updateStatus('oni', 'success', `Loaded ${allData.oni.length} ONI records (CSV)`);
                return allData.oni;
            }
        } catch (csvErr) {
            console.warn('CSV ONI load failed, falling back to text parsing:', csvErr);
        }

        // If CSV loading didn't work, fall back to the original NOAA text format (remote) or local raw
        let response, text;
        try {
            response = await fetch('https://psl.noaa.gov/data/correlation/oni.data');
            if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
            text = await response.text();
        } catch (netErr) {
            console.warn('Primary ONI text fetch failed:', netErr);
            // Try local raw fallback
            try {
                updateStatus('oni', 'loading', 'Primary ONI fetch failed — trying local raw fallback...');
                response = await fetch(LOCAL_ONI_DATA);
                if (!response.ok) throw new Error(`Local ONI fetch error: ${response.status}`);
                text = await response.text();
            } catch (localErr) {
                const msg = `ONI network error: ${netErr.message || netErr}. Local fallback failed: ${localErr.message || localErr}.\n\nPossible causes: no internet, blocked by firewall, or remote server blocks cross-origin requests (CORS).\nOptions: 1) Run the downloader script to create ${ONI_DATA_URL} (python_scripts/download_oni_to_csv.py); 2) Serve this project over HTTP and try again; 3) Allowlist the NOAA domain in your network.`;
                updateStatus('oni', 'error', msg);
                console.error('ONI loading error (both remote and local raw failed):', netErr, localErr);
                return null;
            }
        }

        // Parse the ONI data format (Year followed by 12 monthly values)
        const lines = text.trim().split('\n').filter(line => line.trim() && !line.startsWith('#'));
        const data = [];
        const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
        lines.forEach(line => {
            const values = line.trim().split(/\s+/);
            const year = parseInt(values[0]);
            if (isNaN(year) || year < 1900) return;
            for (let i = 1; i <= 12 && i < values.length; i++) {
                const value = parseFloat(values[i]);
                if (!isNaN(value) && value !== -99.99) {
                    data.push({
                        year: year,
                        month: months[i - 1],
                        monthNum: i,
                        date: new Date(year, i - 1, 1),
                        oni: value,
                        phase: value >= 0.5 ? 'El Niño' : value <= -0.5 ? 'La Niña' : 'Neutral',
                        intensity: Math.abs(value) >= 2.0 ? 'Very Strong' :
                                  Math.abs(value) >= 1.5 ? 'Strong' :
                                  Math.abs(value) >= 1.0 ? 'Moderate' :
                                  Math.abs(value) >= 0.5 ? 'Weak' : 'Neutral'
                    });
                }
            }
        });
        allData.oni = data;
        updateStatus('oni', 'success', `Loaded ${data.length} ONI records (text)`);
        return data;
    } catch (error) {
        updateStatus('oni', 'error', `ONI Error: ${error.message}`);
        console.error('ONI loading error:', error);
        return null;
    }
};

// ==========================================
// 2. WORLD BANK GDP DATA
// ==========================================
const loadGDPData = async (countries = ['PER', 'ECU', 'CHL']) => {
    try {
        updateStatus('gdp', 'loading', 'Loading World Bank GDP data...');
        
        // Build the API URL for multiple countries
        const countryString = countries.join(';');
        const url = `${WORLD_BANK_API_BASE}/country/${countryString}/indicator/${GDP_INDICATOR}?format=json&per_page=1000&date=1990:2024`;
        
        const response = await fetch(url);
        if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
        
        const jsonData = await response.json();
        
        // World Bank returns [metadata, data]
        if (!jsonData || jsonData.length < 2) {
            throw new Error('Invalid World Bank API response');
        }
        
        const rawData = jsonData[1];
        
        // Transform the data
        const data = rawData
            .filter(item => item.value !== null)
            .map(item => ({
                country: item.country.value,
                countryCode: item.countryid,
                year: parseInt(item.date),
                gdpGrowth: parseFloat(item.value),
                indicator: item.indicator.value
            }))
            .sort((a, b) => a.year - b.year);
        
        allData.gdp = data;
        updateStatus('gdp', 'success', `Loaded ${data.length} GDP records for ${countries.length} countries`);
        return data;
        
    } catch (error) {
        updateStatus('gdp', 'error', `GDP Error: ${error.message}`);
        console.error('GDP loading error:', error);
        return null;
    }
};

// ==========================================
// 3. FISHING DATA (Local aggregated CSV: per-country, per-year)
// ==========================================
const loadFishingData = async () => {
    try {
        updateStatus('fishing', 'loading', 'Loading fishing data (aggregated by year)...');

        // The preprocessed CSV `fishing_by_country_year.csv` contains columns like:
        // year,country_un_code,country_iso3,country_name,total_tonnes
        // Accept small variations in column names when parsing.
        const data = await d3.csv(LOCAL_FISHING_DATA, d => {
            const get = (...keys) => {
                for (const k of keys) {
                    if (d[k] !== undefined) return d[k];
                    const low = k.toLowerCase();
                    if (d[low] !== undefined) return d[low];
                    const up = k.toUpperCase();
                    if (d[up] !== undefined) return d[up];
                }
                return undefined;
            };

            const yearRaw = get('year', 'Year');
            const countryUN = get('country_un_code', 'country_un', 'un_code');
            const iso3 = get('country_iso3', 'iso3', 'country_iso');
            const countryName = get('country_name', 'country', 'name');
            const totalRaw = get('total_tonnes', 'total_ton', 'total', 'tonnes', 'value');

            let total = NaN;
            if (totalRaw !== undefined && totalRaw !== null && totalRaw !== '') {
                total = parseFloat(String(totalRaw).replace(/,/g, '').trim());
            }

            return {
                year: yearRaw ? +yearRaw : NaN,
                country_un_code: countryUN || '',
                country_iso3: iso3 || '',
                country_name: countryName || '',
                total_tonnes: isNaN(total) ? null : total
            };
        });

        const cleaned = data.filter(d => d.year && d.country_name && d.total_tonnes !== null && !isNaN(d.total_tonnes));

        allData.fishing = cleaned;
        updateStatus('fishing', 'success', `Loaded ${cleaned.length} fishing records (aggregated by year & country)`);
        return cleaned;

    } catch (error) {
        updateStatus('fishing', 'error', `Fishing Error: ${error.message}. Make sure ${LOCAL_FISHING_DATA} exists and is readable.`);
        console.error('Fishing data error:', error);
        return null;
    }
};

